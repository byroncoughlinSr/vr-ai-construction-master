INSIGHTS_SYSTEM = """You are a sales and client-relationship analyst for a custom home builder.
From CLIENT (their record and recent activity) and PROJECT (if they have one), write insights for the builder.
Use only what is given; leave a list empty rather than guess.
Answer with JSON: {"summary": "3-4 sentences: who they are, what they want, where things stand",
 "preferences": ["what they want in the house, in their words where possible"],
 "risks": ["what could stall or lose the job, or blow the budget or schedule"],
 "next_best_action": "the single most useful next step, concrete",
 "sentiment": "enthusiastic"|"positive"|"neutral"|"concerned"}"""


async def client_insights(planner, db: Session, client: Client, today: date) -> dict:
    project_info = None
    if client.project is not None:
        snap = project_snapshot(db, client.project, today)
        project_info = {k: snap[k] for k in ("project", "floor_plan", "attention")}
        project_info["progress"] = snap["schedule"]["progress"]
    user = f"CLIENT:\n{json.dumps(client_brief(client, 15), default=str)}\n\nPROJECT:\n{json.dumps(project_info, default=str)}"
    data, source = await complete_json(planner, INSIGHTS_SYSTEM, user, "Client insights", max_tokens=700)

    def strings(value: Any) -> list[str]:
        return [_clip(str(v), 300) for v in value if str(v).strip()][:6] if isinstance(value, list) else []

    summary = str(data.get("summary") or "").strip()
    if not summary:
        raise AssistantError("The AI answer had no summary")
    sentiment = data.get("sentiment") if data.get("sentiment") in crm_service.SENTIMENTS else None
    return {
        "summary": _clip(summary, 1500),
        "preferences": strings(data.get("preferences")),
        "risks": strings(data.get("risks")),
        "next_best_action": _clip(str(data.get("next_best_action") or "").strip(), 500) or None,
        "sentiment": sentiment,
        "source": source,
    }


DRAFT_SYSTEM = """You write emails for a custom home builder to their client. Warm, clear and professional;
no hype, no emojis. Plain text, short paragraphs, under 220 words. Use only facts from CLIENT and PROJECT;
where a detail is needed but unknown (a date, a price), write a placeholder in [square brackets].
Action items and the next action are things still to do: never say a change was made, priced or approved unless
PROJECT shows it (a floor plan version or change order). Don't promise a cost or a date that isn't given.
Sign off with SENDER. Answer with JSON: {"subject": "...", "body": "..."}"""


async def draft_email(planner, db: Session, client: Client, purpose: str, notes: Optional[str],
                      sender: Optional[str], today: date) -> dict:
    if purpose not in EMAIL_PURPOSES:
        raise AssistantError(f"Unknown email purpose '{purpose}'")
    project_info = None
    if client.project is not None:
        snap = project_snapshot(db, client.project, today)
        project_info = {
            "project": snap["project"],
            "floor_plan": snap["floor_plan"],
            "progress": snap["schedule"]["progress"],
            "current_phase": snap["schedule"]["current_phase"],
            "planned_finish": snap["schedule"]["planned_finish"],
            "change_orders": snap["change_orders"],
            "upcoming_inspections": snap["compliance"]["upcoming_inspections"],
        }
    user = (
        f"PURPOSE: {EMAIL_PURPOSES[purpose]}\n"
        f"NOTES FROM THE BUILDER: {_clip(notes, 1000) or '(none)'}\n"
        f"SENDER: {_clip(sender, 120) or 'The project team'}\n\n"
        f"CLIENT:\n{json.dumps(client_brief(client, 6), default=str)}\n\n"
        f"PROJECT:\n{json.dumps(project_info, default=str)}"
    )
    data, source = await complete_json(planner, DRAFT_SYSTEM, user, "Email draft", max_tokens=700)
    subject, body = str(data.get("subject") or "").strip(), str(data.get("body") or "").strip()
    if not subject or not body:
        raise AssistantError("The AI answer had no subject or body")
    return {"subject": _clip(subject, 200), "body": body, "source": source}
