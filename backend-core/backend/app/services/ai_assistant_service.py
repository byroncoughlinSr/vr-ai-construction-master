COPILOT_SYSTEM = """You are the AI project manager inside a home builder's dashboard (projects, a sales CRM,
schedule, budget with earned value, permits, and houses designed by voice and walked in VR on a Meta Quest).
SNAPSHOT is the live data. Answer the user's last message from SNAPSHOT only. If SNAPSHOT doesn't hold the
answer, say what is missing and where in the dashboard to add it. Never invent numbers, names, dates or facts.
Be brief and practical, like a senior construction PM: short paragraphs or bullets, markdown (bold, bullets) allowed.
Money in USD. For cost and schedule health use budget.reading, which states what the figures mean; don't reinterpret them.

Answer with JSON: {"reply": "markdown", "actions": [at most 3 actions, or none]}
Offer an action only when it directly helps; the user confirms each one. Action shapes:
- {"type": "refine_floor_plan", "label": "short button text", "instruction": "the change to the house in plain words"}
  (rooms, doors, windows, roof, yard, plants, furniture; only when SNAPSHOT has a floor_plan)
- {"type": "create_task", "label": "...", "phase_id": <id from SNAPSHOT>, "name": "...", "priority": "low"|"medium"|"high"|"critical", "duration_days": n}
- {"type": "draft_email", "label": "...", "client_id": <id from SNAPSHOT>, "purpose": "follow_up"|"vr_invite"|"progress_update"|"change_order"|"proposal"}
- {"type": "create_change_order", "label": "...", "title": "...", "description": "...", "cost_impact": n (0 unless the user gave it)}
- {"type": "navigate", "label": "...", "route": "/"|"/design"|"/crm"|"/timeline"|"/budget"|"/materials"|"/resources"|"/compliance"|"/punch-list"}"""


def clean_actions(actions: Any, phase_ids: set[int], client_ids: set[int], has_floor_plan: bool) -> list[dict]:
    """Keep only well-formed actions that point at things that exist."""
    cleaned: list[dict] = []
    for action in actions if isinstance(actions, list) else []:
        if not isinstance(action, dict) or action.get("type") not in ACTION_TYPES:
            continue
        kind = action["type"]
        label = _clip(str(action.get("label") or kind.replace("_", " ").capitalize()), 60)
        if kind == "refine_floor_plan":
            instruction = str(action.get("instruction") or "").strip()
            if has_floor_plan and instruction:
                cleaned.append({"type": kind, "label": label, "instruction": _clip(instruction, 500)})
        elif kind == "create_task":
            name = str(action.get("name") or "").strip()
            priority = action.get("priority") if action.get("priority") in controls.TASK_PRIORITIES else "medium"
            try:
                days = max(float(action.get("duration_days") or 1), 0.5)
            except (TypeError, ValueError):
                days = 1.0
            if name and action.get("phase_id") in phase_ids:
                cleaned.append({"type": kind, "label": label, "phase_id": action["phase_id"],
                                "name": _clip(name, 255), "priority": priority, "duration_days": days})
        elif kind == "draft_email":
            purpose = action.get("purpose") if action.get("purpose") in EMAIL_PURPOSES else "follow_up"
            if action.get("client_id") in client_ids:
                cleaned.append({"type": kind, "label": label, "client_id": action["client_id"], "purpose": purpose})
        elif kind == "create_change_order":
            title = str(action.get("title") or "").strip()
            try:
                cost = float(action.get("cost_impact") or 0)
            except (TypeError, ValueError):
                cost = 0.0
            if title:
                cleaned.append({"type": kind, "label": label, "title": _clip(title, 255),
                                "description": _clip(str(action.get("description") or ""), 1000),
                                "cost_impact": cost})
        elif kind == "navigate" and action.get("route") in ROUTES:
            cleaned.append({"type": kind, "label": label, "route": action["route"]})
    return cleaned[:3]


async def copilot(planner, db: Session, messages: list[dict], project: Optional[Project],
                  client: Optional[Client], today: date) -> dict:
    snapshot: dict[str, Any] = {"crm": crm_snapshot(db, today)}
    if project is not None:
        snapshot["current_project"] = project_snapshot(db, project, today)
    else:
        snapshot["current_project"] = None
    if client is not None:
        snapshot["focused_client"] = client_brief(client)

    turns = [m for m in messages if m.get("role") in ("user", "assistant") and m.get("content")][-8:]
    conversation = "\n".join(f"{m['role'].upper()}: {_clip(m['content'], 1500)}" for m in turns)
    user = f"SNAPSHOT:\n{json.dumps(snapshot, default=str)}\n\nCONVERSATION:\n{conversation}"
    data, source = await complete_json(planner, COPILOT_SYSTEM, user, "Copilot answer", max_tokens=1000)

    phase_ids = {p["id"] for p in snapshot["current_project"]["schedule"]["phases"]} if project else set()
    client_ids = {c["id"] for c in snapshot["crm"]["clients"]}
    has_plan = bool(project is not None and snapshot["current_project"]["floor_plan"])
    reply = data.get("reply")
    if not isinstance(reply, str) or not reply.strip():
        raise AssistantError("The AI answer had no reply")
    return {
        "reply": reply.strip(),
        "actions": clean_actions(data.get("actions"), phase_ids, client_ids, has_plan),
        "source": source,
    }


