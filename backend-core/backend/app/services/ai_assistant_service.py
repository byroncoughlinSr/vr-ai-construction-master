"""The dashboard's AI: the project copilot, client insights and email drafts.

Runs on the planning service's providers (Groq, then Ollama, then Gemini) but
with short JSON answers instead of a construction plan, so it has its own small
chain (``complete_json``). Every prompt is grounded in a snapshot of what is in
the database and tells the model to say so when the answer isn't there — the
dashboard shows these figures to clients, so nothing may be made up.

Groq's on-demand tier counts ``max_tokens`` against 8,000 tokens a minute:
keep snapshots compact.
"""

from __future__ import annotations

import asyncio
import json
import logging
import time
from datetime import date
from typing import Any, Optional

from sqlalchemy.orm import Session

from ..config import settings
from ..models import Client, Project
from . import crm_service
from . import project_controls_service as controls

logger = logging.getLogger(__name__)

CHAT_TIMEOUT_S = 60.0
ACTION_TYPES = ("refine_floor_plan", "create_task", "draft_email", "create_change_order", "navigate")
ROUTES = ("/", "/design", "/crm", "/timeline", "/budget", "/materials", "/resources", "/compliance", "/punch-list")
EMAIL_PURPOSES = {
    "follow_up": "a friendly follow-up that moves the conversation to the next step",
    "vr_invite": "an invitation to walk through their house in VR on a Meta Quest headset",
    "progress_update": "a construction progress update",
    "change_order": "a summary of a requested change, its cost and schedule effect, asking for approval",
    "proposal": "a cover email for the estimate/proposal",
    "custom": "the message described in the notes",
}


class AssistantError(RuntimeError):
    pass


def _clip(text: Any, limit: int) -> Any:
    if isinstance(text, str) and len(text) > limit:
        return text[: limit - 1] + "…"
    return text


def _parse_json(planner, text: str) -> dict:
    try:
        data = json.loads(text)
    except (TypeError, ValueError):
        data = json.loads(planner._extract_and_repair_json(text))
    if not isinstance(data, dict):
        raise ValueError("answer is not a JSON object")
    return data


async def complete_json(planner, system: str, user: str, what: str, max_tokens: int = 1200) -> tuple[dict, str]:
    """Ask the first provider that answers for a JSON object. Returns
    ``(data, provider)``; raises ``AssistantError`` when none can."""
    loop = asyncio.get_running_loop()

    def groq():
        from groq import BadRequestError
        try:
            response = planner.groq_client.chat.completions.create(
                model=settings.groq_model,
                messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
                temperature=0.4,
                max_tokens=max_tokens,
                response_format={"type": "json_object"},
            )
            return response.choices[0].message.content
        except BadRequestError as e:
            # JSON mode refused the answer; it comes back with the error, often repairable.
            failed = ((getattr(e, "body", None) or {}).get("error") or {}).get("failed_generation")
            if failed:
                return failed
            raise

    def ollama():
        response = planner.ollama_client.chat(
            model=settings.ollama_model,
            messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
            format="json",
            options={"temperature": 0.4, "num_predict": max_tokens, "num_ctx": 6144, "num_thread": 4},
        )
        return response["message"]["content"]

    def gemini():
        import google.generativeai as genai
        response = planner.gemini_model.generate_content(
            f"{system}\n\n{user}",
            generation_config=genai.types.GenerationConfig(
                temperature=0.4, max_output_tokens=max_tokens, response_mime_type="application/json",
            ),
        )
        return response.text

    providers = [
        ("Groq", lambda: planner.groq_available, groq),
        ("Ollama", lambda: planner.ollama_available, ollama),
        ("Gemini", lambda: planner.gemini_available, gemini),
    ]
    deadline = time.monotonic() + CHAT_TIMEOUT_S
    errors = []
    for name, available, call in providers:
        if not available():
            continue
        remaining = deadline - time.monotonic()
        if remaining < 3:
            break
        try:
            text = await asyncio.wait_for(loop.run_in_executor(None, call), timeout=remaining)
            data = _parse_json(planner, text)
            logger.info(f"🧠 {what} generated by {name}")
            return data, name.lower()
        except Exception as e:  # timeout, API error or unparseable answer: try the next one
            logger.warning(f"{what}: {name} failed ({e}); trying next provider")
            errors.append(f"{name}: {e}")
    raise AssistantError("No AI provider could answer" + (f" ({'; '.join(errors)})" if errors else ": none configured"))


# --- snapshots -------------------------------------------------------------

def budget_reading(budget: dict) -> list[str]:
    """The earned value figures in words. Models misread the signs (calling a
    CPI of 0.67 "under budget"), so the meaning is stated, not left to them."""
    lines = []
    cpi, spi = budget.get("cpi"), budget.get("spi")
    if cpi is None:
        lines.append("Cost performance unknown: no expenses logged yet.")
    else:
        verdict = "over budget" if cpi < 1 else "on or under budget"
        lines.append(
            f"Cost: {verdict}. CPI {cpi:.2f} = ${cpi:.2f} of planned work done per $1 spent; "
            f"cost variance ${budget['cost_variance']:,.0f} (negative = overspent for the work done)."
        )
    if spi is None:
        lines.append("Schedule performance unknown: the schedule has no planned dates (not baselined).")
    else:
        verdict = "behind schedule" if spi < 1 else "on or ahead of schedule"
        lines.append(
            f"Schedule: {verdict}. SPI {spi:.2f} = the work done is {spi:.0%} of the work planned by today; "
            f"schedule variance ${budget['schedule_variance']:,.0f}."
        )
    lines.append(
        f"Forecast at completion (EAC = BAC / CPI) ${budget['eac']:,.0f} against a contract value (BAC) of "
        f"${budget['bac']:,.0f}: ${abs(budget['vac']):,.0f} {'over' if budget['vac'] < 0 else 'under'}. "
        f"BAC includes approved change orders only; ${budget['pending_change_orders']:,.0f} more is awaiting approval."
    )
    return lines


def project_snapshot(db: Session, project: Project, today: date) -> dict:
    """What the copilot knows about a project, kept compact."""
    overview = controls.overview(db, project, today)
    budget = {k: v for k, v in overview["budget"].items() if k not in ("by_phase", "by_category")}
    budget["reading"] = budget_reading(overview["budget"])
    phases = []
    for phase in controls.ordered_phases(project):
        open_tasks = [t for t in controls.ordered_tasks(phase) if t.status != "completed"]
        phases.append({
            "id": phase.id,
            "name": phase.name,
            "progress": controls.phase_progress(phase),
            "status": phase.status,
            "planned": [controls.iso(controls.as_date(phase.planned_start_date)),
                        controls.iso(controls.as_date(phase.planned_end_date))],
            "budgeted_cost": phase.budgeted_cost or 0,
            "open_tasks": [
                {"id": t.id, "name": _clip(t.name, 80), "status": t.status, "priority": t.priority}
                for t in open_tasks[:6]
            ],
            "more_open_tasks": max(len(open_tasks) - 6, 0),
        })
    upcoming = [
        controls.serialize_inspection(i) for i in project.inspections or [] if i.status == "scheduled"
    ][:4]
    return {
        "today": today.isoformat(),
        "project": {
            "id": project.id,
            "name": project.name,
            "status": project.status,
            "address": project.address,
            "brief": _clip(project.description, 400),
            "target_budget": project.budget,
        },
        "floor_plan": overview["floor_plan"],
        "schedule": {**overview["schedule"], "phases": phases},
        "budget": budget,
        "change_orders": [
            {k: co[k] for k in ("code", "title", "cost_impact", "schedule_impact_days", "status")}
            for co in (controls.serialize_change_order(c) for c in (project.change_orders or [])[-5:])
        ],
        "compliance": {
            **overview["compliance"],
            "permits": [
                {k: p[k] for k in ("permit_number", "permit_type", "status", "expiration_date")}
                for p in (controls.serialize_permit(p) for p in project.permits or [])
            ][:6],
            "upcoming_inspections": [
                {k: i[k] for k in ("inspection_type", "scheduled_date", "inspector_name")} for i in upcoming
            ],
        },
        "punch_list": {
            **{k: v for k, v in overview["punch_list"].items() if k != "open_by_room"},
            "open_by_room": overview["punch_list"]["open_by_room"][:6],
            "open_items": [
                {"code": f"PL-{p.number:03d}", "title": _clip(p.title, 80), "room": p.room,
                 "status": p.status, "priority": p.priority, "due": controls.iso(p.due_date)}
                for p in (project.punch_items or []) if p.status != "closed"
            ][:6],
        },
        "materials": overview["materials"],
        "attention": [{k: a[k] for k in ("title", "detail")} for a in overview["attention"][:8]],
        "clients": overview["clients"],
    }


def client_brief(client: Client, activities: int = 8) -> dict:
    data = crm_service.serialize_client(client)
    keep = (
        "id", "name", "company", "stage_label", "tier", "deal_value", "win_probability", "site_address",
        "preferred_style", "target_budget", "target_square_feet", "target_completion_date", "requirements",
        "tags", "next_follow_up_at", "next_action", "last_contact_at", "sentiment", "ai_summary", "project_name",
    )
    brief = {k: _clip(data[k], 600) for k in keep if data.get(k) not in (None, "", [])}
    brief["recent_activity"] = [
        {
            "kind": a.kind,
            "when": controls.iso(controls.as_date(a.occurred_at)),
            "summary": _clip(a.summary, 200),
            "details": _clip(a.details, 400),
            "action_items": a.action_items or None,
        }
        for a in (client.activities or [])[:activities]
    ]
    return brief


def crm_snapshot(db: Session, today: date) -> dict:
    clients = db.query(Client).all()
    pipe = crm_service.pipeline(clients, today)
    return {
        "open_leads": pipe["open_count"],
        "open_value": pipe["open_value"],
        "weighted_value": pipe["weighted_value"],
        "by_stage": {s["label"]: s["count"] for s in pipe["stages"] if s["count"]},
        "follow_ups_due": pipe["follow_ups_due"][:6],
        "clients": [{"id": c.id, "name": c.name, "stage": c.stage} for c in clients][:30],
    }


